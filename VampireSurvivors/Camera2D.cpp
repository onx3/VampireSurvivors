#include "AstroidsPrivate.h"
#include "Camera2D.h"

Camera2D::Camera2D(sf::RenderWindow * pWindow)
    : mpWindow(pWindow)
{
    mView = mpWindow->getView();
}

//------------------------------------------------------------------------------------------------------------------------

Camera2D::~Camera2D()
{
}

//------------------------------------------------------------------------------------------------------------------------

void Camera2D::Move(float dx, float dy)
{
    mView.move(dx, dy);
    mpWindow->setView(mView);
}

//------------------------------------------------------------------------------------------------------------------------

void Camera2D::SetPosition(float x, float y)
{
    mView.setCenter(x, y);
    mpWindow->setView(mView);
}

//------------------------------------------------------------------------------------------------------------------------

sf::Vector2f Camera2D::GetPosition() const
{
    return mView.getCenter();
}

//------------------------------------------------------------------------------------------------------------------------

void Camera2D::Zoom(float factor)
{
    mView.zoom(factor);
    mpWindow->setView(mView);
}

//------------------------------------------------------------------------------------------------------------------------

sf::Vector2f Camera2D::ScreenToWorld(const sf::Vector2i & screenPos) const
{
    return sf::Vector2f();
}

//------------------------------------------------------------------------------------------------------------------------

sf::Vector2i Camera2D::WorldToScreen(const sf::Vector2f & worldPos) const
{
    return sf::Vector2i();
}

